std::string libraryReference(const std::string& updated) {
    std::string o = frontmatter("Function library",
                                "Every built-in function, constant and library function the module language offers, generated from the engine.",
                                updated);
    o += "# Function library\n\n";
    o += "Generated by `caw docs` from the engine's own documentation (`engine/src/builtins.cpp` and `engine/lib/*.caw`); "
         "don't edit by hand. The language itself is in [engine](engine.md). A compact version for AI agents is the "
         "[agent guide](agent-guide.md). Every example below is a whole module body (float mode) and CI checks that it "
         "compiles and makes sound.\n\n";
    o += "Optional arguments are marked `?`. Names with a dot belong to a namespace (`env.adsr`, `drum.kick`).\n\n";
    std::vector<DocFn> fns = builtinDocs();
    std::vector<std::string> order;
    for (const DocFn& f : fns)
        if (std::find(order.begin(), order.end(), f.category) == order.end()) order.push_back(f.category);
    for (const std::string& cat : order) {
        o += "## " + cat + "\n\n";
        for (const DocFn& f : fns)
            if (f.category == cat) fnSection(o, f);
    }
    int n = 0;
    const ConstantGroup* groups = constantGroups(n);
    o += "## Constants\n\n";
    for (int g = 0; g < n; ++g) {
        o += "- **`" + std::string(groups[g].prefix) + ".*`**: " + groups[g].doc + " Values: ";
        for (int k = 0; k < groups[g].count; ++k)
            o += std::string(k ? ", " : "") + "`" + groups[g].prefix + "." + groups[g].names[k] + "`";
        o += ".\n";
    }
    o += "\n";
    for (const LibInfo& lib : libraryInfos()) {
        o += "## Library: " + lib.name + " (`" + lib.ns + ".*`)\n\n" + lib.summary +
             ". Written in the module language in `engine/lib/" + lib.ns + ".caw`, so you can read how each one works.\n\n";
        for (const DocFn& f : lib.fns) fnSection(o, f);
    }
    while (o.size() > 1 && o[o.size() - 1] == '\n' && o[o.size() - 2] == '\n') o.pop_back();
    return o;
}

std::string agentGuide(const std::string& updated) {
    std::string o = frontmatter("Agent guide",
                                "Compact guide for AI agents writing C.A.W sound modules: the language in brief and every function on one line.",
                                updated);
    o += "# Agent guide\n\n"
         "Generated by `caw docs`; don't edit by hand. Full details: [engine](engine.md) (language) and "
         "[function library](library.md).\n\n"
         "## Writing a module\n\n"
         "- A `.caw` file: optional header between `---` lines (`caw: 1`, `kind: generator|effect|library`, `name`, "
         "`summary`, `mode: byte|float`, `rate`), then code. The last line is the output.\n"
         "- Byte mode keeps the low 8 bits of the output (`v & 255`); float mode outputs -1..1. Effects read `in`.\n"
         "- Values are 64-bit floats with JavaScript operators; bit operators work on 32-bit integers; `x/0` and `x%0` are 0.\n"
         "- Time: `t`, `time` (s), `step` (16ths), `beat`, `bar`, `pos` (0..1 through the layer's loop), `bpm`, `sr`.\n"
         "- `let x = …`; `param name = 0.5 in 0..1 step 0.1 \"tip\"`, `param on1 = on`, `param w = saw in [sine, saw]` "
         "(read `w.saw`); `global name = …` (shared by the project); `export let env = …` (others read `module.env`); "
         "`fn name(a, b) = …`; `/// docs` above any of them; `// --- Header ---` groups controls.\n"
         "- Check your work without listening: `caw check FILE.caw` and `caw render FILE.caw -o out.wav --bpm 120` "
         "(prints peak and RMS, flags SILENT or CLIPPING).\n\n"
         "## Functions\n\n";
    std::vector<DocFn> fns = builtinDocs();
    for (const LibInfo& lib : libraryInfos())
        for (const DocFn& f : lib.fns) fns.push_back(f);
    for (const DocFn& f : fns) {
        std::string doc = f.doc;
        const size_t dot = doc.find(". ");
        if (dot != std::string::npos) doc = doc.substr(0, dot + 1);
        o += "- `" + signature(f) + "`: " + doc + "\n";
    }
    int n = 0;
    const ConstantGroup* groups = constantGroups(n);
    o += "\n## Constants\n\n";
    for (int g = 0; g < n; ++g) {
        o += "- `" + std::string(groups[g].prefix) + ".`";
        for (int k = 0; k < groups[g].count; ++k) o += std::string(k ? ", " : " ") + groups[g].names[k];
        o += "\n";
    }
    return o;
}

std::string libraryJson() {
    auto str = [](const std::string& v) { return "\"" + jsonEscape(v) + "\""; };
    std::string o = "{\"functions\":[";
    std::vector<DocFn> fns = builtinDocs();
    for (const LibInfo& lib : libraryInfos())
        for (const DocFn& f : lib.fns) fns.push_back(f);
    for (size_t i = 0; i < fns.size(); ++i) {
        const DocFn& f = fns[i];
        o += std::string(i ? "," : "") + "{\"name\":" + str(f.name) + ",\"category\":" + str(f.category) +
             ",\"signature\":" + str(signature(f)) + ",\"doc\":" + str(f.doc) + ",\"example\":" + str(f.example) +
             ",\"args\":[";
        for (size_t a = 0; a < f.args.size(); ++a)
            o += std::string(a ? "," : "") + "{\"name\":" + str(f.args[a]) + ",\"doc\":" + str(f.argDocs[a]) +
                 ",\"optional\":" + (static_cast<int>(a) >= f.required ? "true" : "false") + "}";
        o += "]}";
    }
    o += "],\"constants\":[";
    int n = 0;
    const ConstantGroup* groups = constantGroups(n);
    bool first = true;
    for (int g = 0; g < n; ++g)
        for (int k = 0; k < groups[g].count; ++k) {
            o += std::string(first ? "" : ",") + str(std::string(groups[g].prefix) + "." + groups[g].names[k]);
            first = false;
        }
    return o + "]}";
}

std::vector<std::string> checkLibrary() {
    std::vector<std::string> problems;
    std::vector<DocFn> fns = builtinDocs();
    for (const LibInfo& lib : libraryInfos()) {
        if (lib.ns.empty() || lib.fns.empty()) problems.push_back("a built-in library doesn't compile or has no functions");
        for (const DocFn& f : lib.fns) fns.push_back(f);
    }
    for (const DocFn& f : fns) {
        if (f.doc.empty()) problems.push_back(f.name + ": no description");
        for (size_t a = 0; a < f.args.size(); ++a)
            if (f.args[a].empty() || f.argDocs[a].empty()) problems.push_back(f.name + ": argument " + std::to_string(a + 1) + " isn't described");
        if (f.example.empty()) {
            problems.push_back(f.name + ": no example");
            continue;
        }
        if (f.example.find(f.name + "(") == std::string::npos) problems.push_back(f.name + ": its example doesn't call it");
        // The example must compile and make sound.
        const std::string src = "---\nmode: float\n---\n" + f.example + "\n";
        CompileResult r = compileModule(src);
        if (!r.program) {
            problems.push_back(f.name + ": example doesn't compile: " + r.error);
            continue;
        }
        ProjectSpec p = singleModuleProject(src, 120, 1);
        RenderResult out;
        ExportOptions o;
        if (!renderExport(p, o, out)) {
            problems.push_back(f.name + ": example doesn't render: " + out.error);
            continue;
        }
        float peak = 0;
        for (float v : out.samples) peak = std::fmax(peak, std::fabs(v));
        if (!(peak > 1e-3f)) problems.push_back(f.name + ": example is silent");
    }
    return problems;
}

