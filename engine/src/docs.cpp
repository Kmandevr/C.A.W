struct DocFn {
    std::string name, category, doc, example;
    std::vector<std::string> args, argDocs;
    int required = 0;  // arguments before the optional ones
};

// "freq: Hz" -> ("freq", "Hz")
std::pair<std::string, std::string> splitArg(const char* s) {
    const std::string a = s ? s : "";
    const size_t c = a.find(':');
    if (c == std::string::npos) return {a, ""};
    std::string doc = a.substr(c + 1);
    while (!doc.empty() && doc[0] == ' ') doc.erase(0, 1);
    return {a.substr(0, c), doc};
}

struct LibInfo {
    std::string ns, name, summary;
    std::vector<DocFn> fns;
};

std::vector<DocFn> builtinDocs() {
    std::vector<DocFn> out;
    for (int i = 0; i < builtinCount(); ++i) {
        const Builtin& b = builtin(i);
        DocFn d;
        d.name = b.name;
        d.category = b.category ? b.category : "";
        d.doc = b.doc ? b.doc : "";
        d.example = b.example ? b.example : "";
        d.required = b.minArgs;
        for (int k = 0; k < b.maxArgs; ++k) {
            auto [n, doc] = splitArg(b.args[k]);
            d.args.push_back(n);
            d.argDocs.push_back(doc);
        }
        out.push_back(std::move(d));
    }
    return out;
}

std::vector<LibInfo> libraryInfos() {
    std::vector<LibInfo> out;
    for (const LibrarySource& l : standardLibraries()) {
        CompileResult r = compileModule(l.source);
        LibInfo info;
        if (r.program) {
            info.ns = r.program->ns;
            info.name = r.program->name;
            info.summary = r.program->summary;
        }
        for (const FnDoc& f : libraryDocs(l)) {
            DocFn d;
            d.name = f.name;
            d.category = info.name;
            d.doc = f.doc;
            d.example = f.example;
            d.args = f.args;
            d.argDocs = f.argDocs;
            d.required = static_cast<int>(f.args.size());
            info.fns.push_back(std::move(d));
        }
        out.push_back(std::move(info));
    }
    return out;
}

std::string signature(const DocFn& f) {
    std::string s = f.name + "(";
    for (size_t i = 0; i < f.args.size(); ++i) {
        if (i) s += ", ";
        s += f.args[i];
        if (static_cast<int>(i) >= f.required) s += "?";
    }
    return s + ")";
}

std::string frontmatter(const std::string& title, const std::string& summary, const std::string& updated) {
    return "---\ntitle: " + title + "\nsummary: " + summary + "\nupdated: " + updated + "\n---\n\n";
}

void fnSection(std::string& o, const DocFn& f) {
    o += "### `" + signature(f) + "`\n\n" + f.doc + "\n\n";
    for (size_t i = 0; i < f.args.size(); ++i)
        o += "- `" + f.args[i] + "`" + (static_cast<int>(i) >= f.required ? " (optional)" : "") + ": " + f.argDocs[i] + "\n";
    if (!f.args.empty()) o += "\n";
    if (!f.example.empty()) o += "```\n" + f.example + "\n```\n\n";
}

