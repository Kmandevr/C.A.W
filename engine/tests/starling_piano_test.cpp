// The calibration in src/starling_piano_calibration.inc is what the model measures now: each level within 0.25 dB
// (the fast-math builds differ a little), each alignment within 90 % of the best one now; --update-references
// rewrites it.
TEST(starling_piano_calibration) {
    const std::vector<Measured> now = measureCalibration();
    CHECK(now.size() == static_cast<size_t>(starling::kAttacks));
    if (now.empty()) return;
    if (cawtest::updateGolden) {
#ifdef CAW_ROOT
        const std::string path = std::string(CAW_ROOT) + "/engine/src/starling_piano_calibration.inc";
#else
        const std::string path = "engine/src/starling_piano_calibration.inc";
#endif
        std::ofstream f(path);
        f << "// Generated by caw_tests --update-references starling_piano_calibration (starling_piano_test.cpp): each attack clip's\n"
             "// {model level over the recording's at 110..170 ms, lag in frames, polarity}, in the clips' order.\n"
             "// clang-format off\n"
             "inline constexpr Calibration kCalibration[kAttacks] = {\n";
        char buf[64];
        for (int c = 0; c < starling::kAttacks; ++c) {
            std::snprintf(buf, sizeof buf, "%s{%.5ef, %d, %d},%s", c % 6 == 0 ? "    " : " ", now[c].level, now[c].lag, now[c].sign,
                          c % 6 == 5 ? "\n" : "");
            f << buf;
        }
        f << "};\n// clang-format on\n";
        CHECK(f.good());
        return;
    }
    for (int c = 0; c < starling::kAttacks; ++c) {
        const starling::Calibration& k = starling::kCalibration[c];
        const double d = db(now[c].level) - db(k.level);
        const double aligned = std::abs(k.lag) <= kMaxLag ? now[c].at(k.lag, k.sign) : -1.0;
        if (std::fabs(d) > 0.25 || aligned < 0.9 * now[c].best)
            cawtest::fail(__FILE__, __LINE__, "clip " + std::to_string(c) + ": level " + std::to_string(d) + " dB off, alignment " +
                                                  std::to_string(aligned) + " of " + std::to_string(now[c].best) +
                                                  ": run caw_tests --update-references starling_piano_calibration");
    }
}

// Load only what is used (owner, 2026-11-24): no Starling, no recordings in memory; the last one gone frees them.
TEST(starling_piano_recordings_load_on_use_and_free) {
    CHECK(recorded::residentBytes() == 0);
    {
        auto a = makeStarling({{"variant", 0}});
        CHECK(a != nullptr);
        const size_t one = recorded::residentBytes();
        CHECK(one >= 1416000 * sizeof(float));  // the whole bank decoded once
        auto b = makeStarling({{"variant", 0}});
        CHECK(recorded::residentBytes() == one);  // shared, not decoded again
    }
    CHECK(recorded::residentBytes() == 0);
}

// The recorded attack hands over to the model with no hole or bump: windows across the crossfade (10 ms, or two
// periods in the bass) stay within 4 dB of their neighbours' mean (three velocities over the keyboard).
TEST(starling_piano_crossfade_is_continuous) {
    for (double key : {33.0, 48.0, 60.0, 72.0, 84.0, 96.0}) {
        for (double vel : {0.3, 0.6, 0.9}) {
            const Values v = {{"variant", 0}};
            auto p = makeStarling(v);
            const std::vector<float> m = play(*p, v, {{0.0, -1, key, vel}}, 0.4).mono();
            const size_t n = std::max<size_t>(480, static_cast<size_t>(2 * 48000.0 / (440.0 * std::pow(2.0, (key - 69.0) / 12.0))));
            // From 30 ms to past the crossfade's end (160 ms); each window against the mean of its neighbours.
            double worst = 0;
            for (size_t at = std::max<size_t>(1440, n); at + n < 9600 + n; at += n / 2) {
                const double a = db(rms(m, at - n, n)), b = db(rms(m, at, n)), c = db(rms(m, at + n, n));
                worst = std::max(worst, std::fabs(b - 0.5 * (a + c)));
            }
            if (verbose()) std::printf("key %.0f vel %.1f: worst step %.2f dB\n", key, vel, worst);
            if (worst > 4.0) cawtest::fail(__FILE__, __LINE__, "key " + std::to_string(key) + " vel " + std::to_string(vel) + ": " + std::to_string(worst) + " dB");
        }
    }
}

// The model plays the Salamander Grand's tuning: C7's fundamental about 24 cents sharp, C2's 12 flat.
TEST(starling_piano_is_tuned_as_the_recorded_grand) {
    for (auto [key, cents] : {std::pair{36.0, -11.9}, std::pair{96.0, 23.6}}) {
        const Values v = {{"variant", 0}, {"glide", 0.0}};
        auto p = makeStarling(v);
        modelOf(*p).testMuteRecordings = true;
        const std::vector<float> m = play(*p, v, {{0.0, -1, key, 0.7}}, 1.6).mono();
        const double f0 = 440.0 * std::pow(2.0, (key - 69.0) / 12.0);
        // The strongest frequency within 60 cents of the fundamental, 0.3..1.6 s, by a fine Goertzel sweep.
        double best = 0, at = f0;
        for (double c = -60; c <= 60; c += 0.25) {
            const double hz = f0 * std::pow(2.0, c / 1200.0), w = 2 * timber_test::kPi * hz / 48000.0;
            double re = 0, im = 0;
            for (size_t i = 14400; i < m.size(); ++i) re += m[i] * std::cos(w * i), im += m[i] * std::sin(w * i);
            if (re * re + im * im > best) best = re * re + im * im, at = hz;
        }
        const double got = 1200.0 * std::log2(at / f0);
        if (verbose()) std::printf("key %.0f: %.1f ct (Salamander %.1f)\n", key, got, cents);
        CHECK(std::fabs(got - cents) < 2.5);
    }
}

// Releasing a key plays its recorded release noise and the pedal its recorded noise, scaled by Noise: what Noise
// adds after the key-up (its recordings and the dampers' simulated buzz) is far more with the recordings than
// without.
TEST(starling_piano_plays_its_recorded_noises) {
    auto render = [](double noise, bool muteRecordings) {
        const Values v = {{"variant", 0}, {"noise", noise}};
        auto p = makeStarling(v);
        modelOf(*p).testMuteRecordings = muteRecordings;
        return play(*p, v, {{0.0, 0.25, 60, 0.7}}, 0.7, 48000, 64, {{0.4, 64, 1.0}}).mono();
    };
    auto added = [&](bool mute, size_t from, size_t n) {
        const std::vector<float> a = render(1.0, mute), b = render(0.0, mute);
        std::vector<float> d(a.size());
        for (size_t i = 0; i < a.size(); ++i) d[i] = a[i] - b[i];
        return rms(d, from, n);
    };
    const double rel = added(false, 12000, 4800), relModel = added(true, 12000, 4800);  // 250..350 ms
    const double ped = added(false, 19200, 9600), pedModel = added(true, 19200, 9600);  // 400..600 ms
    if (verbose()) std::printf("release %.1f dB (model alone %.1f); pedal %.1f dB (model alone %.1f)\n", db(rel), db(relModel), db(ped), db(pedModel));
    CHECK(rel > 2.0 * relModel);
    CHECK(ped > 4.0 * pedModel);
}

// The three characters are three pianos (the owner, 2026-11-25: "the simulation is not different for the Felt or the
// Upright", and the Felt measured brighter than the grand). Compared loudness-normalised (a level alone is not a
// difference): the spectral centroid of the 1/3-octave band energies and those energies (125 Hz..16 kHz, their mean taken off, RMS) over
// 0.05..0.8 s, the attack time (to 3 dB under the peak of a 1 ms envelope) and the T60 (the envelope's slope over
// 0.15..0.75 s). The Felt is darker and slower to speak than the grand, the Upright shorter-lived, every pair apart in
// colour; each plays the recorded attack. The owner's phrase: 48, 60, 72, 84 at 0.7, held 0.8 s.
TEST(starling_piano_characters_are_three_pianos) {
    struct M {
        double centroid = 0, attackMs = 0, t60 = 0, band[24] = {};
        double lvl = 0, bright = 0, early = 0, late = 0, tail = 0;  // the owner's columns (printed)
    };
    auto measure = [](double character, bool muted) {
        const Values v = {{"variant", 0}, {"character", character}};
        auto p = makeStarling(v);
        if (muted) modelOf(*p).testMuteRecordings = true;
        std::vector<Note> n;
        for (double k : {48.0, 60.0, 72.0, 84.0}) n.push_back({0.0, 0.8, k, 0.7});
        std::vector<float> m = play(*p, v, n, 1.5).mono();
        M r;
        auto lv = [&](double a, double b) { return db(rms(m, static_cast<size_t>(a * 48000), static_cast<size_t>((b - a) * 48000))); };
        std::vector<float> d(m.size());
        for (size_t i = 1; i < m.size(); ++i) d[i] = m[i] - m[i - 1];
        r.lvl = lv(0, 0.8), r.bright = db(rms(d, 0, 38400)) - r.lvl, r.early = lv(0, 0.1), r.late = lv(0.6, 0.8), r.tail = lv(0.9, 1.5);
        const double g = 1.0 / std::max(1e-9, rms(m, 0, 38400));  // loudness-normalised from here on
        for (float& x : m) x = static_cast<float>(x * g);
        for (int b = 0; b < 24; ++b) {
            timber::Biquad q;
            q.band(125.0 * std::pow(2.0, b / 3.0), 4.32, 48000);
            double e = 0;
            for (size_t i = 0; i < 38400; ++i) {
                const float y = q.run(m[i]);
                if (i >= 2400) e += static_cast<double>(y) * y;
            }
            r.band[b] = 10 * std::log10(e + 1e-30);
        }
        double num = 0, den = 0;  // the centroid over the bands' energies (a DFT grid misses the partials between its bins)
        for (int b = 0; b < 24; ++b) {
            const double e = std::pow(10.0, r.band[b] / 10), hz = 125.0 * std::pow(2.0, b / 3.0);
            num += hz * e, den += e;
        }
        r.centroid = num / den;
        std::vector<double> env;
        for (size_t i = 0; i + 48 <= 38400; i += 48) env.push_back(rms(m, i, 48));
        const double top = *std::max_element(env.begin(), env.end());
        for (size_t i = 0; i < env.size(); ++i)
            if (env[i] >= top * 0.7079) {
                r.attackMs = static_cast<double>(i);
                break;
            }
        const double e0 = db(rms(m, 7200, 4800)), e1 = db(rms(m, 31200, 4800));  // 0.15..0.25 s and 0.65..0.75 s
        r.t60 = e1 < e0 ? 60.0 * 0.5 / (e0 - e1) : 99.0;
        return std::make_pair(r, m);
    };
    auto distance = [](const M& a, const M& b) {
        double mean = 0, e = 0;
        for (int k = 0; k < 24; ++k) mean += (a.band[k] - b.band[k]) / 24.0;
        for (int k = 0; k < 24; ++k) e += std::pow(a.band[k] - b.band[k] - mean, 2) / 24.0;
        return std::sqrt(e);
    };
    const auto [grand, g] = measure(0, false);
    const auto [upright, u] = measure(1, false);
    const auto [felt, f] = measure(2, false);
    const char* names[3] = {"Grand", "Upright", "Felt"};
    const M* all[3] = {&grand, &upright, &felt};
    if (verbose())
        for (int c = 0; c < 3; ++c)
            std::printf("%-8s centroid %.0f Hz, attack %.0f ms, T60 %.2f s | lvl %.1f bright %.1f early %.1f late %.1f tail %.1f dB\n", names[c],
                        all[c]->centroid, all[c]->attackMs, all[c]->t60, all[c]->lvl, all[c]->bright, all[c]->early, all[c]->late, all[c]->tail);
    const double gu = distance(grand, upright), gf = distance(grand, felt), uf = distance(upright, felt);
    if (verbose()) std::printf("1/3-octave distance: grand-upright %.1f, grand-felt %.1f, upright-felt %.1f dB\n", gu, gf, uf);
    CHECK(felt.centroid < 0.75 * grand.centroid);    // darker
    CHECK(felt.centroid < 0.75 * upright.centroid);
    CHECK(felt.attackMs > grand.attackMs + 2.0);     // slower to speak (the felt rail)
    CHECK(upright.t60 < 0.8 * grand.t60);            // shorter-lived
    CHECK(gu > 1.5 && gf > 3.0 && uf > 3.0);         // three colours
    // Both play the recorded attack (muting the recordings changes them).
    for (double c : {1.0, 2.0}) CHECK(measure(c, true).second != (c == 1.0 ? u : f));
}

// The same bits at any block size, through the crossfade, the release and the pedal.
TEST(starling_piano_gives_the_same_bits_at_any_block_size) {
    const Values v = {{"variant", 0}, {"noise", 0.8}, {"action", 1}};
    const std::vector<Note> n = {{0.0, 0.25, 40, 0.8}, {0.05, 0.3, 64, 0.5}, {0.11, 0.4, 88, 0.95}};
    Stereo ref;
    for (uint32_t block : {64u, 1u, 37u, 512u}) {
        auto p = makeStarling(v);
        const Stereo s = play(*p, v, n, 0.6, 48000, block, {{0.2, 64, 1.0}, {0.45, 64, 0.0}});
        if (block == 64) ref = s;
        else CHECK(same(s, ref));
    }
}

// Every preset loads and plays something finite.
TEST(starling_presets_load_and_play) {
    const std::vector<BuiltinPreset>* list = starling::starlingPresets(kStarling);
    CHECK(list && list->size() >= 6);
    if (!list) return;
    for (const BuiltinPreset& pr : *list) {
        Values v;
        for (const auto& [k, x] : pr.values) v.emplace_back(std::string(k), x);
        auto p = makeStarling(v);
        CHECK(p != nullptr);
        if (!p) continue;
        const std::vector<float> m = play(*p, v, {{0.0, 0.2, 60, 0.7}}, 0.3).mono();
        double peak = 0;
        for (float x : m) peak = std::max(peak, static_cast<double>(std::fabs(x)));
        CHECK(std::isfinite(peak) && peak > 1e-3 && peak < 4.0);
    }
}

TEST(starling_piano_matches_its_reference_render) {
    cawtest::References refs("starling_piano");
    const Values v = {{"variant", 0}, {"noise", 0.6}};
    auto p = makeStarling(v);
    const Stereo s = play(*p, v, {{0.0, 0.5, 33, 0.9}, {0.1, 0.6, 55, 0.6}, {0.2, 0.9, 64, 0.75}, {0.3, 0.7, 88, 0.4}}, 1.2, 48000, 64,
                          {{0.4, 64, 1.0}, {0.8, 64, 0.0}});
    CHECK_REFERENCE(refs, "starling_piano", (cawtest::Audio{s.l, s.r}), cawtest::Class::Chaotic);
}
