constexpr const char* kStarling = "org.caw.starling";

std::unique_ptr<ModuleProcessor> makeStarling(const Values& v, double sr = 48000) {
    std::unique_ptr<ModuleProcessor> p = createComponent(registry(), kStarling, v);
    if (p && !p->activate(sr, 512)) p.reset();
    return p;
}
starling::PianoModel& modelOf(ModuleProcessor& p) {
    return static_cast<timber::Instrument<starling::PianoModel>&>(p).model();
}
double rms(const std::vector<float>& x, size_t from, size_t n) {
    double s = 0;
    for (size_t i = from; i < from + n && i < x.size(); ++i) s += static_cast<double>(x[i]) * x[i];
    return std::sqrt(s / static_cast<double>(n));
}
double db(double x) { return 20.0 * std::log10(std::max(x, 1e-12)); }
bool same(const Stereo& a, const Stereo& b) { return a.l == b.l && a.r == b.r; }

// The model alone (recordings muted) at velocity sensitivity 1, so a voice's velocity is the note's, and Noise 0, so
// its simulated thump and keybed (which the recording replaces) are off.
const Values kCalibrate = {{"velocity", 1.0}, {"noise", 0.0}, {"variant", 0}};

constexpr int kMaxLag = 96;  // 2 ms at 48 kHz
struct Measured {
    double level = 1;  // the model's mono RMS over 110..170 ms over the recording's as the player places it
    int lag = 0, sign = 1;
    double best = 0;          // the best alignment's correlation (normalised)
    std::vector<double> corr;  // every lag's, by lag + kMaxLag
    double at(int l, int s) const { return s * corr[static_cast<size_t>(l + kMaxLag)]; }
};

// Each attack clip against the model playing its note alone: the level over 110..170 ms (the voice's mono gain is
// (panL + panR) / 2) and the lag and polarity that best line it up with the model over 40..160 ms.
std::vector<Measured> measureCalibration() {
    std::vector<Measured> out(starling::kAttacks);
    const auto bank = recorded::acquire(recorded::BankId::StarlingPiano);
    if (!bank) return {};
    for (int c = 0; c < starling::kAttacks; ++c) {
        const starling::Clip& k = starling::kPianoClips[c];
        auto p = makeStarling(kCalibrate);
        if (!p) return {};
        modelOf(*p).testMuteRecordings = true;
        const std::vector<float> m = play(*p, kCalibrate, {{0.0, -1, static_cast<double>(k.key), k.vel / 127.0}}, 0.18).mono();
        const double pan = std::clamp((k.key - 64.0) / 44.0, -1.0, 1.0) * timber::Piano::kSpread;
        const double pl = std::cos((pan + 1.0) * 0.25 * timber_test::kPi), pr = std::sin((pan + 1.0) * 0.25 * timber_test::kPi);
        Measured& r = out[c];
        r.level = rms(m, 5280, 2880) / (0.5 * (pl + pr) * k.rms);
        const float* x = bank->pcm.get() + k.first;
        double mm = 0, xx = 0;
        for (size_t n = 1920; n < 7680; ++n) mm += static_cast<double>(m[n]) * m[n], xx += static_cast<double>(x[n]) * x[n];
        r.corr.assign(2 * kMaxLag + 1, 0.0);
        for (int lag = -kMaxLag; lag <= kMaxLag; ++lag) {
            double s = 0;
            for (size_t n = 1920; n < 7680; ++n) {
                const long i = static_cast<long>(n) - lag;
                if (i >= 0 && i < static_cast<long>(k.frames)) s += static_cast<double>(m[n]) * x[i];
            }
            const double c1 = s / std::sqrt(mm * xx + 1e-30);
            r.corr[static_cast<size_t>(lag + kMaxLag)] = c1;
            if (std::fabs(c1) > r.best) r.best = std::fabs(c1), r.lag = lag, r.sign = c1 < 0 ? -1 : 1;
        }
    }
    return out;
}

